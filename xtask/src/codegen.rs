//! `cargo xtask codegen`: Python models for the tool servers (blueprint 7.1, 13.2).
//!
//! For each `schemas/tools/<server>/` with a matching `mcp_servers/<server>/`,
//! regenerates `mcp_servers/<server>/models/<server>_models/`:
//!
//! - `*_schema.py`: pydantic models, written by datamodel-code-generator at
//!   the version pinned in the server's `uv.lock` (dependency group `codegen`);
//! - `schemas/<stem>.schema.json`: each schema with its `$ref`s inlined into
//!   `$defs`. MCP needs self-contained schemas, and this is what the server
//!   advertises and validates against;
//! - `py.typed`.
//!
//! `--check` generates into a temporary directory and fails if anything
//! differs from the committed files, so CI catches drift. Line endings are
//! compared as LF, since Git may check files out with CRLF.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::{Map, Value};

const HEADER_TEMPLATE: &str =
    "# @generated by `cargo xtask codegen` from schemas/tools/{server}/. Do not edit.";

pub fn run(root: &Path, check: bool) -> Result<()> {
    let servers = servers(root)?;
    if servers.is_empty() {
        bail!("no schemas/tools/<server>/ has a matching mcp_servers/<server>/");
    }
    ensure_uv()?;
    let mut drift = Vec::new();
    for server in &servers {
        let scratch = tempfile::tempdir().context("creating a temporary directory")?;
        let generated = generate(root, server, scratch.path())?;
        let package = package_dir(root, server);
        if check {
            drift.extend(compare(root, &package, &generated)?);
        } else {
            write(&package, &generated)?;
            eprintln!(
                "xtask: codegen: wrote {} files to {}",
                generated.len(),
                relative(root, &package)
            );
        }
    }
    if !drift.is_empty() {
        bail!(
            "generated code differs from schemas/ (run `cargo xtask codegen`):\n  - {}",
            drift.join("\n  - ")
        );
    }
    if check {
        eprintln!("xtask: codegen --check: generated code is up to date");
    }
    Ok(())
}

/// Server names that have both a schema directory and a server directory.
fn servers(root: &Path) -> Result<Vec<String>> {
    let tools = root.join("schemas/tools");
    let mut names = Vec::new();
    for entry in fs::read_dir(&tools).with_context(|| format!("reading {}", tools.display()))? {
        let path = entry?.path();
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if path.is_dir() && root.join("mcp_servers").join(name).is_dir() {
            names.push(name.to_owned());
        }
    }
    names.sort();
    Ok(names)
}

fn package_dir(root: &Path, server: &str) -> PathBuf {
    root.join("mcp_servers")
        .join(server)
        .join("models")
        .join(format!("{server}_models"))
}

/// Generates every file of the models package, keyed by path relative to it.
fn generate(root: &Path, server: &str, scratch: &Path) -> Result<BTreeMap<String, String>> {
    let schema_dir = root.join("schemas/tools").join(server);
    let schemas = schema_files(&schema_dir)?;

    // Only the schema files go to the generator: examples/ is data.
    let input = scratch.join("input");
    fs::create_dir_all(&input)?;
    for (name, text) in &schemas {
        fs::write(input.join(name), text)?;
    }
    let output = scratch.join("output");
    let header = HEADER_TEMPLATE.replace("{server}", server);
    let status = uv()
        .current_dir(root)
        .args(["run", "--project"])
        .arg(root.join("mcp_servers").join(server))
        .args(["--frozen", "--only-group", "codegen", "datamodel-codegen"])
        .arg("--input")
        .arg(&input)
        .arg("--output")
        .arg(&output)
        .args([
            "--input-file-type",
            "jsonschema",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.12",
            "--use-annotated",
            "--field-constraints",
            "--extra-fields",
            "forbid",
            "--use-title-as-name",
            "--use-schema-description",
            "--use-field-description",
            "--disable-timestamp",
            "--formatters",
            "builtin",
            "--custom-file-header",
            &header,
        ])
        .status()
        .context("failed to start uv")?;
    if !status.success() {
        bail!("datamodel-codegen failed for {server} ({status})");
    }

    // Marks the models as typed, so the server's strict type check covers them.
    let mut files = BTreeMap::from([("py.typed".to_owned(), String::new())]);
    for entry in fs::read_dir(&output)? {
        let path = entry?.path();
        let name = file_name(&path)?;
        if path.extension().is_some_and(|e| e == "py") {
            files.insert(name, lf(&fs::read_to_string(&path)?));
        }
    }

    let parsed = schemas
        .iter()
        .map(|(name, text)| {
            serde_json::from_str(text)
                .map(|v| (name.clone(), v))
                .with_context(|| format!("schemas/tools/{server}/{name}: invalid JSON"))
        })
        .collect::<Result<BTreeMap<String, Value>>>()?;
    for name in parsed.keys() {
        let bundled = bundle(&parsed, name)
            .with_context(|| format!("bundling schemas/tools/{server}/{name}"))?;
        let text = serde_json::to_string_pretty(&bundled)? + "\n";
        files.insert(format!("schemas/{name}"), text);
    }
    Ok(files)
}

fn schema_files(dir: &Path) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    for entry in fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        let name = file_name(&path)?;
        if path.is_file() && name.ends_with(".schema.json") {
            files.insert(name, lf(&fs::read_to_string(&path)?));
        }
    }
    Ok(files)
}

/// What a `$ref` points at: a file's root type, or one of its `$defs`.
#[derive(Clone)]
enum Target {
    Root,
    Def(String),
}

/// Inlines every `$ref` of `root_file` into one `$defs` map.
///
/// References must stay inside the server's schema directory, so the server
/// package needs nothing else. A root type is added under its `title`, a
/// definition under its own name; names are already unique across `schemas/`
/// (schema-types fails the build otherwise), and a clash is still an error.
fn bundle(files: &BTreeMap<String, Value>, root_file: &str) -> Result<Value> {
    let mut root = files
        .get(root_file)
        .cloned()
        .context("schema file is missing")?;
    let Value::Object(root_map) = &mut root else {
        bail!("{root_file}: not a JSON object");
    };
    let root_defs = match root_map.remove("$defs") {
        Some(Value::Object(defs)) => defs,
        Some(_) => bail!("{root_file}: `$defs` is not an object"),
        None => Map::new(),
    };

    let mut queue = Vec::new();
    rewrite(&mut root, root_file, root_file, files, &mut queue)?;
    let mut defs = Map::new();
    let mut origin: BTreeMap<String, String> = BTreeMap::new();
    for (name, mut schema) in root_defs {
        rewrite(&mut schema, root_file, root_file, files, &mut queue)?;
        origin.insert(name.clone(), root_file.to_owned());
        defs.insert(name, schema);
    }

    while let Some((file, target)) = queue.pop() {
        let source = files
            .get(&file)
            .with_context(|| format!("$ref to {file}, which is not in this directory"))?;
        let (name, mut schema) = match &target {
            Target::Root => {
                let title = source
                    .get("title")
                    .and_then(Value::as_str)
                    .with_context(|| format!("$ref to {file}, which has no root type"))?;
                let mut schema = source.clone();
                if let Value::Object(map) = &mut schema {
                    map.remove("$schema");
                    map.remove("$defs");
                }
                (title.to_owned(), schema)
            }
            Target::Def(name) => {
                let schema = source
                    .get("$defs")
                    .and_then(|d| d.get(name))
                    .cloned()
                    .with_context(|| format!("$ref to {file}#/$defs/{name}, which is missing"))?;
                (name.clone(), schema)
            }
        };
        if let Some(previous) = origin.get(&name) {
            if *previous != file {
                bail!("`{name}` is defined in both {previous} and {file}");
            }
            continue;
        }
        rewrite(&mut schema, &file, root_file, files, &mut queue)?;
        origin.insert(name.clone(), file.clone());
        defs.insert(name, schema);
    }

    if !defs.is_empty()
        && let Value::Object(map) = &mut root
    {
        map.insert("$defs".to_owned(), Value::Object(defs));
    }
    Ok(root)
}

/// Rewrites the `$ref`s in `value`, which comes from `file`, to point into
/// the bundled `$defs`, and queues what they point at.
fn rewrite(
    value: &mut Value,
    file: &str,
    root_file: &str,
    files: &BTreeMap<String, Value>,
    queue: &mut Vec<(String, Target)>,
) -> Result<()> {
    match value {
        Value::Object(map) => {
            if let Some(Value::String(reference)) = map.get_mut("$ref") {
                let (file_part, fragment) = reference
                    .split_once('#')
                    .unwrap_or((reference.as_str(), ""));
                if file_part.contains('/') {
                    bail!("{file}: `$ref` {reference} leaves the server's schema directory");
                }
                let target_file = if file_part.is_empty() {
                    file.to_owned()
                } else {
                    file_part.to_owned()
                };
                let rewritten = if let Some(name) = fragment.strip_prefix("/$defs/") {
                    if name.contains('/') {
                        bail!("{file}: nested `$ref` {reference} is not supported");
                    }
                    if target_file != root_file {
                        queue.push((target_file, Target::Def(name.to_owned())));
                    }
                    format!("#/$defs/{name}")
                } else if fragment.is_empty() {
                    if target_file == root_file {
                        "#".to_owned()
                    } else {
                        let title = files
                            .get(&target_file)
                            .and_then(|s| s.get("title"))
                            .and_then(Value::as_str)
                            .with_context(|| {
                                format!("{file}: `$ref` {reference} names no root type")
                            })?
                            .to_owned();
                        queue.push((target_file, Target::Root));
                        format!("#/$defs/{title}")
                    }
                } else {
                    bail!("{file}: `$ref` {reference} is not supported");
                };
                *reference = rewritten;
            }
            for child in map.values_mut() {
                rewrite(child, file, root_file, files, queue)?;
            }
        }
        Value::Array(items) => {
            for item in items {
                rewrite(item, file, root_file, files, queue)?;
            }
        }
        _ => {}
    }
    Ok(())
}

/// Differences between the committed package and freshly generated files.
fn compare(
    root: &Path,
    package: &Path,
    generated: &BTreeMap<String, String>,
) -> Result<Vec<String>> {
    let committed = read_tree(package)?;
    let mut drift = Vec::new();
    for (path, text) in generated {
        let shown = relative(root, &package.join(path));
        match committed.get(path) {
            None => drift.push(format!("{shown}: missing")),
            Some(existing) if existing != text => drift.push(format!("{shown}: out of date")),
            Some(_) => {}
        }
    }
    for path in committed.keys().filter(|p| !generated.contains_key(*p)) {
        drift.push(format!(
            "{}: not generated from any schema",
            relative(root, &package.join(path))
        ));
    }
    Ok(drift)
}

/// Replaces the package with the generated files.
fn write(package: &Path, generated: &BTreeMap<String, String>) -> Result<()> {
    if package.exists() {
        fs::remove_dir_all(package).with_context(|| format!("removing {}", package.display()))?;
    }
    for (path, text) in generated {
        let target = package.join(path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&target, text).with_context(|| format!("writing {}", target.display()))?;
    }
    Ok(())
}

/// Text files under `dir`, keyed by `/`-separated relative path, with LF
/// line endings. Python caches are skipped.
fn read_tree(dir: &Path) -> Result<BTreeMap<String, String>> {
    fn walk(base: &Path, dir: &Path, out: &mut BTreeMap<String, String>) -> Result<()> {
        if !dir.exists() {
            return Ok(());
        }
        for entry in fs::read_dir(dir)? {
            let path = entry?.path();
            if path.is_dir() {
                if path.file_name().is_some_and(|n| n != "__pycache__") {
                    walk(base, &path, out)?;
                }
            } else {
                let key = path
                    .strip_prefix(base)?
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect::<Vec<_>>()
                    .join("/");
                out.insert(key, lf(&fs::read_to_string(&path)?));
            }
        }
        Ok(())
    }
    let mut out = BTreeMap::new();
    walk(dir, dir, &mut out)?;
    Ok(out)
}

fn lf(text: &str) -> String {
    text.replace("\r\n", "\n")
}

fn file_name(path: &Path) -> Result<String> {
    path.file_name()
        .and_then(|n| n.to_str())
        .map(str::to_owned)
        .with_context(|| format!("{}: unreadable file name", path.display()))
}

fn relative(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

/// The uv binary: `UV` if set, else `uv` on PATH.
fn uv() -> Command {
    Command::new(std::env::var_os("UV").unwrap_or_else(|| "uv".into()))
}

fn ensure_uv() -> Result<()> {
    let found = uv()
        .arg("--version")
        .output()
        .is_ok_and(|out| out.status.success());
    if !found {
        bail!(
            "uv is not installed; install it (https://docs.astral.sh/uv/) or point the UV \
             environment variable at its binary"
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn files(entries: &[(&str, Value)]) -> BTreeMap<String, Value> {
        entries
            .iter()
            .map(|(n, v)| ((*n).to_owned(), v.clone()))
            .collect()
    }

    #[test]
    fn inlines_roots_and_definitions_of_other_files() {
        let set = files(&[
            (
                "a.schema.json",
                json!({
                    "$schema": "x",
                    "title": "A",
                    "properties": {
                        "b": { "$ref": "b.schema.json" },
                        "c": { "$ref": "b.schema.json#/$defs/C" },
                        "own": { "$ref": "#/$defs/Own" }
                    },
                    "$defs": { "Own": { "type": "number" } }
                }),
            ),
            (
                "b.schema.json",
                json!({
                    "$schema": "x",
                    "title": "B",
                    "properties": { "c": { "$ref": "#/$defs/C" } },
                    "$defs": { "C": { "type": "string" } }
                }),
            ),
        ]);
        let bundled = bundle(&set, "a.schema.json").unwrap();
        assert_eq!(
            bundled,
            json!({
                "$schema": "x",
                "title": "A",
                "properties": {
                    "b": { "$ref": "#/$defs/B" },
                    "c": { "$ref": "#/$defs/C" },
                    "own": { "$ref": "#/$defs/Own" }
                },
                "$defs": {
                    "Own": { "type": "number" },
                    "B": { "title": "B", "properties": { "c": { "$ref": "#/$defs/C" } } },
                    "C": { "type": "string" }
                }
            })
        );
    }

    #[test]
    fn references_outside_the_directory_are_rejected() {
        let set = files(&[(
            "a.schema.json",
            json!({ "title": "A", "properties": { "q": { "$ref": "../common/q.schema.json" } } }),
        )]);
        assert!(bundle(&set, "a.schema.json").is_err());
    }

    #[test]
    fn a_name_defined_in_two_files_is_rejected() {
        let set = files(&[
            (
                "a.schema.json",
                json!({
                    "title": "A",
                    "properties": { "x": { "$ref": "b.schema.json#/$defs/X" } },
                    "$defs": { "X": { "type": "number" } }
                }),
            ),
            (
                "b.schema.json",
                json!({ "title": "B", "$defs": { "X": { "type": "string" } } }),
            ),
        ]);
        assert!(bundle(&set, "a.schema.json").is_err());
    }
}
