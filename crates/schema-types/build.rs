//! Generates Rust types from every `*.schema.json` under `schemas/`.
//!
//! typify does not follow references across files, so the schemas are first
//! bundled into one `$defs` map: each file's root type is added under its
//! `title`, each file's own `$defs` are added under their names, and every
//! `$ref` is rewritten to `#/$defs/<name>`. Names must therefore be unique
//! across all schema files; a duplicate fails the build.

use std::collections::BTreeMap;
use std::error::Error;
use std::fs;
use std::path::{Component, Path, PathBuf};

use serde_json::{Map, Value};

type BuildResult<T> = Result<T, Box<dyn Error>>;

fn main() -> BuildResult<()> {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let schemas_dir = manifest_dir.join("../../schemas");
    println!("cargo:rerun-if-changed={}", schemas_dir.display());

    let files = load_schema_files(&schemas_dir)?;
    let definitions = bundle(&files)?;

    let root: schemars::schema::RootSchema =
        serde_json::from_value(serde_json::json!({ "$defs": definitions }))?;
    let mut settings = typify::TypeSpaceSettings::default();
    settings.with_struct_builder(false);
    // Lets stores and tests compare stored and retrieved values directly.
    settings.with_derive("PartialEq".to_string());
    let mut type_space = typify::TypeSpace::new(&settings);
    type_space.add_root_schema(root)?;

    let file: syn::File = syn::parse2(type_space.to_stream())?;
    let source = format!(
        "// @generated by crates/schema-types/build.rs from schemas/. Do not edit.\n\n{}",
        prettyplease::unparse(&file)
    );
    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);
    fs::write(out_dir.join("schema_types.rs"), source)?;
    fs::write(
        out_dir.join("schema_files.rs"),
        schema_files_table(&schemas_dir, &files),
    )?;
    Ok(())
}

/// An array expression pairing each schema's path relative to `schemas/` with
/// its text, embedded with `include_str!` so it is the file as it is on disk.
fn schema_files_table(schemas_dir: &Path, files: &[SchemaFile]) -> String {
    let entries: String = files
        .iter()
        .map(|f| {
            let path = schemas_dir.join(&f.rel_path);
            format!(
                "    ({:?}, include_str!({:?})),\n",
                f.rel_path,
                path.display().to_string()
            )
        })
        .collect();
    format!("&[\n{entries}]\n")
}

struct SchemaFile {
    /// Path relative to `schemas/`, with `/` separators.
    rel_path: String,
    content: Value,
}

fn load_schema_files(schemas_dir: &Path) -> BuildResult<Vec<SchemaFile>> {
    let mut paths = Vec::new();
    collect_schema_paths(schemas_dir, &mut paths)?;
    paths.sort();
    paths
        .into_iter()
        .map(|path| {
            let rel_path = path
                .strip_prefix(schemas_dir)?
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            let text = fs::read_to_string(&path)?;
            let content = serde_json::from_str(&text)
                .map_err(|e| format!("schemas/{rel_path}: invalid JSON: {e}"))?;
            Ok(SchemaFile { rel_path, content })
        })
        .collect()
}

fn collect_schema_paths(dir: &Path, out: &mut Vec<PathBuf>) -> BuildResult<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            // Example instances are data, not schemas.
            if path.file_name().is_some_and(|n| n != "examples") {
                collect_schema_paths(&path, out)?;
            }
        } else if path
            .file_name()
            .is_some_and(|n| n.to_string_lossy().ends_with(".schema.json"))
        {
            out.push(path);
        }
    }
    Ok(())
}

fn bundle(files: &[SchemaFile]) -> BuildResult<Map<String, Value>> {
    // A file's root type is named by its title; files without one hold only `$defs`.
    let root_titles: BTreeMap<&str, String> = files
        .iter()
        .filter_map(|f| {
            let title = f.content.get("title")?.as_str()?;
            Some((f.rel_path.as_str(), title.to_string()))
        })
        .collect();

    let mut definitions = Map::new();
    let mut origin: BTreeMap<String, String> = BTreeMap::new();
    for file in files {
        let Value::Object(mut root) = file.content.clone() else {
            return Err(format!("schemas/{}: not a JSON object", file.rel_path).into());
        };
        root.remove("$schema");
        let local_defs = match root.remove("$defs") {
            Some(Value::Object(defs)) => defs,
            Some(_) => {
                return Err(format!("schemas/{}: `$defs` is not an object", file.rel_path).into());
            }
            None => Map::new(),
        };

        let mut entries: Vec<(String, Value)> = local_defs.into_iter().collect();
        if let Some(title) = root_titles.get(file.rel_path.as_str()) {
            entries.push((title.clone(), Value::Object(root)));
        }
        for (name, mut schema) in entries {
            rewrite_refs(&mut schema, &file.rel_path, &root_titles)?;
            if let Some(previous) = origin.insert(name.clone(), file.rel_path.clone()) {
                return Err(format!(
                    "type name `{name}` is defined in both schemas/{previous} and schemas/{}",
                    file.rel_path
                )
                .into());
            }
            definitions.insert(name, schema);
        }
    }
    Ok(definitions)
}

/// Rewrites every `$ref` in `value` to point into the bundled `$defs` map.
fn rewrite_refs(
    value: &mut Value,
    current_file: &str,
    root_titles: &BTreeMap<&str, String>,
) -> BuildResult<()> {
    match value {
        Value::Object(map) => {
            if let Some(Value::String(reference)) = map.get_mut("$ref") {
                *reference = bundled_ref(reference, current_file, root_titles)?;
            }
            for child in map.values_mut() {
                rewrite_refs(child, current_file, root_titles)?;
            }
        }
        Value::Array(items) => {
            for item in items {
                rewrite_refs(item, current_file, root_titles)?;
            }
        }
        _ => {}
    }
    Ok(())
}

fn bundled_ref(
    reference: &str,
    current_file: &str,
    root_titles: &BTreeMap<&str, String>,
) -> BuildResult<String> {
    let (file_part, fragment) = reference.split_once('#').unwrap_or((reference, ""));
    let target_file = if file_part.is_empty() {
        current_file.to_string()
    } else {
        resolve_relative(current_file, file_part)
    };

    if let Some(name) = fragment.strip_prefix("/$defs/") {
        if name.contains('/') {
            return Err(
                format!("schemas/{current_file}: unsupported nested $ref `{reference}`").into(),
            );
        }
        return Ok(format!("#/$defs/{name}"));
    }
    if fragment.is_empty() {
        let title = root_titles.get(target_file.as_str()).ok_or_else(|| {
            format!("schemas/{current_file}: $ref `{reference}` targets a file without a root type")
        })?;
        return Ok(format!("#/$defs/{title}"));
    }
    Err(format!("schemas/{current_file}: unsupported $ref `{reference}`").into())
}

/// Resolves `relative` against the directory of `current_file`, both relative to `schemas/`.
fn resolve_relative(current_file: &str, relative: &str) -> String {
    let mut parts: Vec<String> = Path::new(current_file)
        .parent()
        .map(|p| {
            p.components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    for component in Path::new(relative).components() {
        match component {
            Component::ParentDir => {
                parts.pop();
            }
            Component::Normal(part) => parts.push(part.to_string_lossy().into_owned()),
            _ => {}
        }
    }
    parts.join("/")
}
